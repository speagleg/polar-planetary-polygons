def weinberg_angle(N=4):
    """Compute the Weinberg angle from the polygon framework.

    sin²θ_W = Y² / [Y² + C₂/(N-1)]

    At N=4: Y = m*/N = 1/2, C₂/(N-1) = f(2,4)/3 = 2/3
    sin²θ_W = 3/11 ≈ 0.2727

    Returns dict with the derivation.
    """
    m_crit = N // 2
    Y = m_crit / N  # KK hypercharge
    f_crit = casimir(m_crit, N)
    C2_norm = f_crit / (N - 1)  # normalized Casimir

    sin2_theta = Y**2 / (Y**2 + C2_norm)

    return {
        'N': N,
        'Y': Y,
        'C2_normalized': C2_norm,
        'sin2_theta_W': sin2_theta,
        'exact_fraction': '3/11' if N == 4 else f'{Y**2}/{Y**2 + C2_norm}',
        'numerical': sin2_theta,
        'experimental': 0.23122,
        'su5_gut': 3 / 8,
        'discrepancy_pct': abs(sin2_theta - 0.23122) / 0.23122 * 100,
        'su5_discrepancy_pct': abs(3 / 8 - 0.23122) / 0.23122 * 100,
    }


