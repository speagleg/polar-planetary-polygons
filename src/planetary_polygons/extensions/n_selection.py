from math import sqrt, gcd


def casimir(m, N):
    return m * (N - m) / 2.0


def critical_spin(N):
    """Compute the spin j at the critical mode of the N-polygon.

    Returns (j, is_integer, m_star, f_star).
    """
    m_star = N // 2
    f = casimir(m_star, N)
    j = (-1 + sqrt(1 + 4 * f)) / 2
    j_int = int(round(j))
    is_integer = abs(j - j_int) < 1e-10
    return j, is_integer, m_star, f


def integer_spin_polygons(N_max=100):
    """Find all polygon numbers N ≤ N_max with integer critical spin.

    Returns list of (N, j) tuples.
    """
    results = []
    for N in range(3, N_max + 1):
        j, is_int, _, _ = critical_spin(N)
        if is_int:
            results.append((N, int(round(j))))
    return results


def pell_solutions(n_solutions=10):
    """Generate solutions of N² - 2y² = -1 (negative Pell equation).

    The solutions are generated by ε = 1+√2 (fundamental unit of Z[√2]):
    (N_k + y_k √2) = (1+√2)^(2k-1) for k = 1, 2, 3, ...

    Returns list of (N, y, j) where j = (y-1)/2.
    """
    solutions = []
    x, y = 1, 1  # ε^1 = 1 + √2
    solutions.append((x, y, (y - 1) // 2))

    for _ in range(n_solutions - 1):
        # Multiply by ε² = 3 + 2√2:
        # (x + y√2)(3 + 2√2) = (3x+4y) + (2x+3y)√2
        x_new = 3 * x + 4 * y
        y_new = 2 * x + 3 * y
        x, y = x_new, y_new
        j = (y - 1) // 2
        solutions.append((x, y, j))

    return solutions


def verify_pell(N, j):
    """Verify N² - 2(2j+1)² = -1."""
    y = 2 * j + 1
    return N * N - 2 * y * y == -1


def even_N_integer_spin(k_max=20):
    """Find even N with integer critical spin.

    For even N = 4k: j(j+1) = 2k².
    Need j integer, so 1+8k² must be a perfect square.

    Returns list of (N, k, j) tuples.
    """
    results = []
    for k in range(1, k_max + 1):
        N = 4 * k
        val = 1 + 8 * k * k
        sq = int(round(sqrt(val)))
        if sq * sq == val:
            j = (sq - 1) // 2
            if j * (j + 1) == 2 * k * k:
                results.append((N, k, j))
    return results


