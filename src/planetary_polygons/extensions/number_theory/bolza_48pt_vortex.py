"""
Full 48-point vortex computation on the Bolza surface.

THE SETUP:
- 48 = |Aut(Bolza)| = |GL(2, F_3)|
- Take a GENERIC point z_0 in the fundamental domain
- Its orbit under the 48 automorphisms gives 48 distinct points
- The 48×48 interaction matrix, with the automorphic Green's function,
  decomposes under the regular representation of GL(2, F_3)
- The regular representation contains ALL irreps (each with multiplicity = dim)
- The 2D irreps appear with multiplicity 2 -> eigenvalue degeneracy of 2

THE AUTOMORPHISM GROUP:
GL(2, F_3) has order 48. Its elements act on the Poincare disc as
Mobius transformations (isometries of H²).

Generators in the Poincare disc model:
  R = rotation by π/4: z -> z * exp(iπ/4)  [order 8]
  J = inversion + rotation: z -> (specific Mobius)  [order 2 or 3]

The group is generated by:
  R (rotation by π/4), S (reflection), and the hyperelliptic involution.

For the OCTAGON fundamental domain:
  - Rotations by kπ/4 (k = 0,...,7) give the cyclic part Z/8Z
  - Reflections give the dihedral part D_8
  - The hyperelliptic involution J: z -> -z (in centered octagon coords)
  - Side-pairing transformations: 4 hyperbolic translations

THE GREEN'S FUNCTION:
The automorphic Green's function is:
  G(z, w) = Σ_{γ ∈ Γ} g(d(z, γw))
where g(d) = -(1/2π) log|tanh(d/2)| and Γ is the fundamental group.

For computational efficiency: include lattice images up to distance D_max.
The sum converges exponentially since g(d) ~ -d/(4π) for large d.
"""

import numpy as np
from math import pi, sin, cos, log, sqrt, exp, atan2, cosh, sinh, acosh, tanh, atanh


# =====================================================================
# Poincare disc utilities
# =====================================================================

def hyp_dist_disc(z1, z2):
    """Hyperbolic distance in the Poincare disc."""
    num = abs(z1 - z2)
    den = abs(1 - np.conj(z1) * z2)
    if den < 1e-15:
        return float('inf')
    ratio = num / den
    if ratio >= 1 - 1e-15:
        return 30.0  # cap at large distance
    return 2 * atanh(ratio)


def mobius(z, a, b, c, d):
    """Mobius transformation (az+b)/(cz+d) on the disc."""
    num = a * z + b
    den = c * z + d
    if abs(den) < 1e-15:
        return 1e10 + 1e10j
    return num / den


def havelock_kernel(d):
    """The vortex interaction kernel: -log(2 sinh(d/2))."""
    if d < 1e-10:
        return 0.0  # regularized self-energy
    if d > 30:
        return -d / 2 - log(2)  # asymptotic
    return -log(2 * sinh(d / 2))


