def build_automorphisms():
    """Build the 48 elements of Aut(Bolza) as Poincare disc isometries."""
    print("=" * 72)
    print("  PART 1: THE 48 AUTOMORPHISMS OF THE BOLZA SURFACE")
    print("=" * 72)

    # In the Poincare disc with the regular octagon centered at 0:
    # The automorphisms that FIX the center are the dihedral group D_8
    # (rotations by kπ/4 and reflections).
    #
    # The FULL automorphism group includes the hyperelliptic involution
    # and compositions with it.
    #
    # For the regular octagon:
    # Rotation R_k: z -> z * exp(ikπ/4)  for k = 0,...,7  (8 elements)
    # Reflection σ: z -> conj(z)  (across the real axis)
    # Combined: R_k ∘ σ: z -> conj(z) * exp(ikπ/4)  (8 more elements)
    # Total from D_8: 16 elements
    #
    # The hyperelliptic involution J: z -> -z (negation in the disc)
    # This commutes with rotations but anticommutes with some reflections.
    #
    # Combined with D_8: J, R_k∘J, σ∘J, R_k∘σ∘J  (16 more elements)
    # Total: 32 elements
    #
    # But we need 48, not 32. The remaining 16 come from the
    # SIDE-PAIRING TRANSFORMATIONS of the octagon.
    #
    # Actually, GL(2, F_3) has order 48 = 16 × 3.
    # The 3 comes from a Z/3Z quotient.
    # For the octagon: there are elements of order 3 (120° rotations
    # around the VERTEX, not the center).

    # Let me use a simpler approach: generate the group from
    # explicit Mobius transformations.

    # The key generators of Aut(Bolza) in the disc model:
    # 1. R = rotation by π/4: z -> z * omega, omega = exp(iπ/4)
    # 2. S = complex conjugation: z -> conj(z) (reflection)
    # 3. T = a translation that maps one edge to the opposite
    #    (a hyperbolic translation along a geodesic through the center)

    omega = np.exp(1j * pi / 4)

    # Generate rotations and reflections (D_8, order 16)
    elements = []
    labels = []

    for k in range(8):
        # Rotation by kπ/4
        rot = omega**k
        elements.append(('rot', rot))
        labels.append(f"R^{k}")

    for k in range(8):
        # Rotation by kπ/4 followed by conjugation (= reflection)
        rot = omega**k
        elements.append(('ref', rot))
        labels.append(f"R^{k}S")

    # Now add the hyperelliptic involution J: z -> -z
    # and its compositions with D_8
    for k in range(8):
        rot = omega**k
        elements.append(('rot_neg', rot))  # z -> -z * rot
        labels.append(f"JR^{k}")

    for k in range(8):
        rot = omega**k
        elements.append(('ref_neg', rot))  # z -> -conj(z) * rot
        labels.append(f"JR^{k}S")

    # That gives 32 elements. For the remaining 16:
    # We need a side-pairing transformation.
    # The side-pairing for the octagon identifies side k with side k+4.
    # This is a hyperbolic translation along the geodesic connecting
    # the midpoints of opposite sides.

    # The side-pairing transformation T for side 0 -> side 4:
    # This is a Mobius transformation that maps the midpoint of side 0
    # to the midpoint of side 4.

    # For the regular octagon: the midpoint of side 0 is at
    # the real axis, at distance R*cos(π/8) from center.
    # The midpoint of side 4 is at the negative real axis.

    # The side-pairing: T maps m_0 to m_4, which is z -> -z (wait, that's J).
    # No: the side-pairing is a TRANSLATION, not an inversion.

    # For a regular octagon with opposite side identification:
    # The side-pairings are hyperbolic translations by 2*a (twice the
    # distance from center to edge midpoint along the geodesic).

    # Let me just work with the 32 elements from D_8 × Z/2Z.
    # This gives a subgroup of index 48/32 = 3/2... no, 32 doesn't divide 48.
    # 48 = 16 × 3. The 16 is the D_8, the 3 is from the order-3 element.

    # Actually the structure of GL(2, F_3):
    # |GL(2, F_3)| = (9-1)(9-3) = 8×6 = 48.
    # It has a normal subgroup SL(2, F_3) of order 24 (binary tetrahedral).
    # SL(2, F_3) = 2T = binary tetrahedral = <a,b | a^3 = b^3 = (ab)^2>

    # For the Bolza surface: the automorphism group is generated by
    # three involutions. Let me use a concrete presentation.

    # USE THE 32 ELEMENTS WE HAVE (D_8 × Z/2 subgroup of index 3/2)
    # Wait, 32 doesn't divide 48. Let me reconsider.

    # Actually D_8 has order 16, not 8. And D_8 × Z/2 has order 32.
    # The full group has order 48 = 32 × 3/2... not exact.
    # 48 = 2^4 × 3. The Sylow 2-subgroup has order 16 (= D_8 or Q_16).
    # The Sylow 3-subgroup has order 3.

    # For computational purposes: let me use the 32 elements from
    # rotations/reflections/negation. This captures D_8 × Z/2.
    # The missing 16 elements involve the order-3 vertex rotations.

    # For a FIRST computation: use 32 points (from D_8 × Z/2 orbit).
    # This is a subgroup of Aut(Bolza) and will show partial degeneracies.

    n_elem = len(elements)
    print(f"  Generated {n_elem} group elements (D_8 × Z/2 subgroup)")
    print(f"  (Full Aut(Bolza) has 48 elements; missing the order-3 part)")

    return elements, labels


def apply_automorphism(z, elem):
    """Apply a group element to a point z in the disc."""
    typ, rot = elem
    if typ == 'rot':
        return z * rot
    elif typ == 'ref':
        return np.conj(z) * rot
    elif typ == 'rot_neg':
        return -z * rot
    elif typ == 'ref_neg':
        return -np.conj(z) * rot
    return z


