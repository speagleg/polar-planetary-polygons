def lattice_sum_interaction():
    """Include fundamental group images in the Green's function."""
    print(f"\n{'='*72}")
    print("  PART 3: LATTICE SUM (AUTOMORPHIC GREEN'S FUNCTION)")
    print("=" * 72)

    print("""
  The DIRECT interaction only uses one copy of each point.
  The AUTOMORPHIC Green's function sums over all Γ-images:

    G(z, w) = Σ_{γ ∈ Γ} g(d(z, γw))

  The fundamental group Γ of the Bolza surface is generated by
  4 side-pairings: A, B, C, D with the relation [A,B][C,D] = 1.

  Each side-pairing is a hyperbolic translation by distance 2a
  (where a ≈ 2.448 is the edge length).

  The NEAREST Γ-images are at distance ≈ 2a ≈ 4.9 from the
  fundamental domain. Since g(d) ~ -d/2 for large d, these
  contribute ~ -2.4 to the interaction (small compared to the
  direct term ~ 0.5 for nearby points).

  For a FIRST APPROXIMATION: include the 8 nearest images
  (one per side of the octagon) plus the 16 next-nearest.
  This captures > 99% of the lattice sum for well-separated points.
""")

    elements, labels = build_automorphisms()

    # Generic base point
    z0 = 0.15 + 0.08j

    # Generate the orbit under D_8 × Z/2
    orbit = []
    for elem in elements:
        w = apply_automorphism(z0, elem)
        if abs(w) < 0.99:
            orbit.append(w)

    unique = [orbit[0]]
    for w in orbit[1:]:
        is_dup = any(abs(w - u) < 1e-10 for u in unique)
        if not is_dup:
            unique.append(w)
    orbit = unique
    n = len(orbit)

    # The side-pairing translations:
    # For a regular octagon centered at 0, the side-pairing T_k maps
    # edge k to edge k+4. In the Poincare disc, this is a Mobius
    # transformation that translates along the geodesic through the
    # midpoints of edges k and k+4.

    # The midpoint of edge k is at distance R*cos(π/8) from center,
    # at angle kπ/4. The geodesic through m_k and m_{k+4} passes
    # through the center (since they're diametrically opposite).

    # So T_k is a HYPERBOLIC TRANSLATION along the line through 0
    # at angle kπ/4, by distance 2 * R_mid (twice the center-to-midpoint distance).

    R_disc = 0.810465
    mid_r = R_disc * cos(pi / 8)  # Euclidean distance of midpoint from center

    # Hyperbolic distance of midpoint from center:
    mid_hyp = 2 * atanh(mid_r)

    # Translation distance = 2 * mid_hyp (from midpoint to its pair)
    trans_dist = 2 * mid_hyp

    print(f"  Edge midpoint distance: {mid_hyp:.6f} (hyperbolic)")
    print(f"  Translation distance: {trans_dist:.6f}")
    print(f"  Kernel at translation distance: {havelock_kernel(trans_dist):.6f}")

    # The side-pairing T_k translates z along the geodesic at angle kπ/4.
    # In the Poincare disc: translation by distance d along the real axis is:
    #   z -> (z + t)/(1 + conj(t)*z) where t = tanh(d/2)
    # For angle θ: rotate, translate, rotate back.

    t_param = tanh(trans_dist / 2)

    def translate(z, angle, dist):
        """Translate z by hyperbolic distance dist along direction angle."""
        t = tanh(dist / 2)
        # Rotate to real axis, translate, rotate back
        z_rot = z * np.exp(-1j * angle)
        z_trans = (z_rot + t) / (1 + t * np.conj(z_rot))
        return z_trans * np.exp(1j * angle)

    # Generate the 4 independent translations and their inverses (8 total)
    translations = []
    for k in range(4):
        angle = k * pi / 4
        translations.append((angle, trans_dist))
        translations.append((angle, -trans_dist))

    print(f"  Generated {len(translations)} side-pairing translations")

    # Compute the LATTICE-SUMMED interaction matrix
    # For each pair (i, j): add contributions from the 8 nearest Γ-images
    print(f"\n  Computing lattice-summed {n}×{n} matrix...")
    print(f"  (including {len(translations)} nearest images per point)")

    M_lattice = np.zeros((n, n))
    for i in range(n):
        for j in range(n):
            if i == j:
                # Self-energy: sum over non-identity Γ-images
                total = 0.0
                for angle, dist in translations:
                    w_image = translate(orbit[j], angle, dist)
                    d = hyp_dist_disc(orbit[i], w_image)
                    total += havelock_kernel(d)
                M_lattice[i][j] = total
            else:
                # Direct + image contributions
                d_direct = hyp_dist_disc(orbit[i], orbit[j])
                total = havelock_kernel(d_direct)
                for angle, dist in translations:
                    w_image = translate(orbit[j], angle, dist)
                    d = hyp_dist_disc(orbit[i], w_image)
                    total += havelock_kernel(d)
                M_lattice[i][j] = total

    # Eigenvalues
    eigenvalues = np.linalg.eigvalsh(M_lattice)
    eigenvalues = sorted(eigenvalues, reverse=True)

    print(f"\n  Eigenvalues of the lattice-summed {n}×{n} matrix:")
    for i, ev in enumerate(eigenvalues):
        print(f"    λ_{i:2d} = {ev:14.10f}")

    # Degeneracy analysis
    print(f"\n  Degeneracy analysis (tolerance 10^-3):")
    groups = []
    used = set()
    for i in range(n):
        if i in used:
            continue
        group = [i]
        for j in range(i+1, n):
            if j in used:
                continue
            if abs(eigenvalues[i] - eigenvalues[j]) < 1e-3:
                group.append(j)
                used.add(j)
        used.add(i)
        groups.append((eigenvalues[group[0]], len(group)))

    print(f"  {'eigenvalue':>14s} {'mult':>6s} {'type':>20s}")
    for ev, mult in groups:
        if mult == 1:
            rep = "1D"
        elif mult == 2:
            rep = "*** 2D IRREP ***"
        elif mult == 3:
            rep = "3D"
        elif mult == 4:
            rep = "4D (2×2D?)"
        else:
            rep = f"{mult}D"
        print(f"  {ev:14.8f} {mult:6d} {rep:>20s}")

    n_2d = sum(1 for _, m in groups if m == 2)
    if n_2d > 0:
        print(f"\n  *** FOUND {n_2d} TWO-DIMENSIONAL IRREPS ***")
        for ev, m in groups:
            if m == 2:
                print(f"  *** GL(2) eigenvalue candidate: {ev:.10f} ***")


