def orbit_interaction():
    """Generate the orbit of a generic point and compute interactions."""
    print(f"\n{'='*72}")
    print("  PART 2: ORBIT INTERACTION MATRIX")
    print("=" * 72)

    elements, labels = build_automorphisms()

    # Choose a generic point (not on any symmetry axis)
    z0 = 0.15 + 0.08j  # generic, inside the octagon

    # Generate the orbit
    orbit = []
    for elem in elements:
        w = apply_automorphism(z0, elem)
        # Check it's inside the disc
        if abs(w) < 0.99:
            orbit.append(w)

    # Remove duplicates (points closer than 1e-10)
    unique = [orbit[0]]
    for w in orbit[1:]:
        is_dup = False
        for u in unique:
            if abs(w - u) < 1e-10:
                is_dup = True
                break
        if not is_dup:
            unique.append(w)

    orbit = unique
    n = len(orbit)
    print(f"\n  Base point: z_0 = {z0}")
    print(f"  Orbit size: {n} distinct points (from {len(elements)} group elements)")

    if n < 10:
        print(f"  Orbit points:")
        for i, w in enumerate(orbit):
            print(f"    z_{i} = {w.real:+.6f} {w.imag:+.6f}i, |z| = {abs(w):.6f}")

    # Compute the interaction matrix (DIRECT, no lattice sum yet)
    print(f"\n  Computing {n}×{n} interaction matrix (direct kernel)...")

    M = np.zeros((n, n))
    for i in range(n):
        for j in range(n):
            if i == j:
                M[i][j] = 0  # regularized
            else:
                d = hyp_dist_disc(orbit[i], orbit[j])
                M[i][j] = havelock_kernel(d)

    # Eigenvalues
    eigenvalues = np.linalg.eigvalsh(M)
    eigenvalues = sorted(eigenvalues, reverse=True)

    print(f"\n  Eigenvalues of the {n}×{n} interaction matrix:")
    for i, ev in enumerate(eigenvalues):
        print(f"    λ_{i:2d} = {ev:14.10f}")

    # Degeneracy analysis
    print(f"\n  Degeneracy analysis (tolerance 10^-4):")
    groups = []
    used = set()
    for i in range(n):
        if i in used:
            continue
        group = [i]
        for j in range(i+1, n):
            if j in used:
                continue
            if abs(eigenvalues[i] - eigenvalues[j]) < 1e-4:
                group.append(j)
                used.add(j)
        used.add(i)
        groups.append((eigenvalues[group[0]], len(group)))

    print(f"  {'eigenvalue':>14s} {'multiplicity':>14s} {'irrep type':>20s}")
    for ev, mult in groups:
        if mult == 1:
            rep = "1D (trivial/sign)"
        elif mult == 2:
            rep = "2D irrep (!)"
        elif mult == 3:
            rep = "3D irrep"
        elif mult == 4:
            rep = "4D (2×2D or other)"
        else:
            rep = f"{mult}D"
        print(f"  {ev:14.8f} {mult:14d} {rep:>20s}")

    # Count the irreps
    n_1d = sum(1 for _, m in groups if m == 1)
    n_2d = sum(1 for _, m in groups if m == 2)
    n_3d = sum(1 for _, m in groups if m == 3)
    n_4d = sum(1 for _, m in groups if m == 4)
    n_other = sum(1 for _, m in groups if m > 4)

    print(f"\n  Irrep content: {n_1d}×1D + {n_2d}×2D + {n_3d}×3D + "
          f"{n_4d}×4D + {n_other}×(higher)")
    print(f"  Total: {sum(m for _, m in groups)} (should be {n})")

    if n_2d > 0:
        print(f"\n  *** 2D IRREDUCIBLE REPRESENTATIONS FOUND: {n_2d} ***")
        for ev, mult in groups:
            if mult == 2:
                print(f"  *** GL(2) eigenvalue = {ev:.10f} ***")

    return orbit, eigenvalues, groups


