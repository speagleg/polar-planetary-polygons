def n7_functional_equation(a_n, a_P):
    """Test the functional equation of the N=7 L-function."""
    print(f"\n{'='*72}")
    print("  PART 4: FUNCTIONAL EQUATION OF THE N=7 L-FUNCTION")
    print("=" * 72)

    print("""
  For a GL(2) form over K at level 1 (trivial level, since h_K = 1):
  The conductor is |d_K| = 49.

  Lambda(s) = (49/pi^2)^{s/2} Gamma_C(s)^3 L(s)  [over K, degree 2]
  where Gamma_C(s) = 2(2pi)^{-s} Gamma(s).

  For the BASE CHANGE to Q (degree 6):
  Lambda(s, BC) = (49^3/pi^6)^{s/2} Gamma(s/2)^6 L(s, BC)

  Test: Lambda(s) vs Lambda(1-s).
""")

    # Compute L(s) and L(1-s) for the multiplicative coefficients
    def L_at(sigma, t=0):
        total = sum(a_n[n] / n**sigma * cos(-t * log(n)) if n > 0 else 0
                    for n in range(1, 200))
        return total

    # Test the FE at sigma = 1/2
    from math import lgamma
    cond = 49  # conductor (discriminant of K)

    print(f"  Testing Lambda(s) = (49/pi^2)^{{s/2}} Gamma(s/2)^2 L(s):")
    print(f"  (Using degree-2 L-function with conductor 49)\n")
    print(f"  {'sigma':>8s} {'L(s)':>12s} {'L(1-s)':>12s} "
          f"{'log|Lambda(s)|':>16s} {'log|Lambda(1-s)|':>18s} {'diff':>10s}")

    for sigma in [0.5, 0.3, 0.7, 0.2, 0.8, 0.1, 0.9]:
        L_s = L_at(sigma)
        L_1s = L_at(1 - sigma)

        # Lambda = (49/pi^2)^{s/2} Gamma(s/2)^2 L(s)
        log_cond = sigma / 2 * log(cond / pi**2)
        log_gamma = 2 * lgamma(max(sigma/2, 0.001))
        log_Lambda_s = log_cond + log_gamma + log(abs(L_s)) if abs(L_s) > 1e-50 else -999

        log_cond_1 = (1-sigma) / 2 * log(cond / pi**2)
        log_gamma_1 = 2 * lgamma(max((1-sigma)/2, 0.001))
        log_Lambda_1s = log_cond_1 + log_gamma_1 + log(abs(L_1s)) if abs(L_1s) > 1e-50 else -999

        diff = log_Lambda_s - log_Lambda_1s

        print(f"  {sigma:8.2f} {L_s:12.6f} {L_1s:12.6f} "
              f"{log_Lambda_s:16.6f} {log_Lambda_1s:18.6f} {diff:10.6f}")

    # Try with conductor 7 instead of 49
    print(f"\n  Testing with conductor 7:")
    for sigma in [0.5, 0.3, 0.7, 0.2, 0.8]:
        L_s = L_at(sigma)
        L_1s = L_at(1 - sigma)

        log_cond = sigma / 2 * log(7 / pi)
        log_gamma = lgamma(max(sigma/2, 0.001))
        log_Lambda_s = log_cond + log_gamma + log(abs(L_s)) if abs(L_s) > 1e-50 else -999

        log_cond_1 = (1-sigma) / 2 * log(7 / pi)
        log_gamma_1 = lgamma(max((1-sigma)/2, 0.001))
        log_Lambda_1s = log_cond_1 + log_gamma_1 + log(abs(L_1s)) if abs(L_1s) > 1e-50 else -999

        diff = log_Lambda_s - log_Lambda_1s
        print(f"  {sigma:8.2f}  diff = {diff:10.6f}")


