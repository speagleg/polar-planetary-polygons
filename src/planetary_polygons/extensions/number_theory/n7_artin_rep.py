def cm_test(a_n):
    """Determine if the form is CM or non-CM."""
    print(f"\n{'='*72}")
    print("  PART 5: CM OR NON-CM?")
    print("=" * 72)

    print("""
  A form is CM if it's induced from a Hecke character of a CM extension.
  For a form over K = Q(cos 2pi/7): CM means there exists an imaginary
  quadratic extension L/K such that the form is induced from a character of L.

  TESTS for CM:
  1. The Hecke eigenvalues at inert primes should be 0 (for CM).
  2. The density of nonzero a_p should be 1/[L:K] = 1/2 (for CM).
  3. The distribution should be discrete, not Sato-Tate.

  For our form:
""")

    # Count zero vs nonzero a_p
    primes = [p for p in range(2, 200)
              if all(p % d != 0 for d in range(2, int(sqrt(p))+1))]

    n_zero = 0
    n_nonzero = 0
    nonzero_vals = set()

    for p in primes:
        if p < 200 and abs(a_n[p]) < 1e-10:
            n_zero += 1
        else:
            n_nonzero += 1
            nonzero_vals.add(round(a_n[p], 6))

    print(f"  Primes with a_p = 0: {n_zero} ({100*n_zero/(n_zero+n_nonzero):.1f}%)")
    print(f"  Primes with a_p != 0: {n_nonzero} ({100*n_nonzero/(n_zero+n_nonzero):.1f}%)")
    print(f"  Distinct nonzero values: {len(nonzero_vals)}")
    print(f"  Values: {sorted(nonzero_vals)}")

    # For CM: we expect 50% zero (inert in L/K)
    # For non-CM: we expect very few zeros

    # Count by class mod 7
    print(f"\n  Distribution by p mod 7:")
    for r in range(1, 7):
        count = sum(1 for p in primes if p % 7 == r)
