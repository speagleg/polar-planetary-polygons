def n7_lfunction(v1, v2, v3):
    """Compute the L-function of the N=7 Havelock form."""
    print(f"\n{'='*72}")
    print("  PART 3: THE L-FUNCTION OF THE N=7 FORM")
    print("=" * 72)

    N = 7
    S = {m: havelock_eigenvalue(m, N) for m in range(1, N)}
    S_max = max(abs(S[m]) for m in range(1, N))
    C = S_max / 2.0

    # The Hecke eigenvalues at rational primes:
    # p = 1, 6 mod 7 (split): a_p determined by p mod 7 -> mode 1
    # p = 2, 5 mod 7 (inert[2]): a_p determined by mode 2
    # p = 3, 4 mod 7 (inert[3]): a_p determined by mode 3

    # The Havelock "Hecke eigenvalue" at prime p:
    # For the D_1(s) = sum a_m / m^s extended periodically with period 7:
    # a_p = a_{p mod 7} (the Havelock eigenvalue at mode p mod 7)

    print(f"  The THREE Hecke eigenvalue classes:")
    print(f"  p = 1, 6 mod 7: a_p = a_1/C = {S[1]/C:.10f}")
    print(f"  p = 2, 5 mod 7: a_p = a_2/C = {S[2]/C:.10f}")
    print(f"  p = 3, 4 mod 7: a_p = a_3/C = {S[3]/C:.10f}")
    print(f"  p = 7:           a_p = 0 (ramified)")

    # The L-function: L(s) = prod_p (1 - a_p p^{-s} + p^{-2s})^{-1}
    # For split primes: two Satake parameters alpha, beta with alpha+beta = a_p, alpha*beta = 1
    # For inert primes: similar but with different local factor

    # Compute L(s) as a Dirichlet series with periodic coefficients
    print(f"\n  L(s) = prod_p (1 - a_p p^{{-s}} + p^{{-2s}})^{{-1}}")
    print(f"\n  First 30 Dirichlet coefficients a_n:")
    print(f"  {'n':>5s} {'a_n':>12s} {'n mod 7':>8s}")

    # For this GL(2) L-function: a_n is multiplicative.
    # a_p = Havelock eigenvalue at p mod 7
    # a_{p^2} = a_p^2 - 1 (Hecke relation with chi(p) = 1)
    # a_{p^k} = a_p * a_{p^{k-1}} - a_{p^{k-2}}

    def a_prime(p):
        if p == 7:
            return 0
        r = p % 7
        if r > 3:
            r = 7 - r
        return S[r] / C

    # Compute a_n multiplicatively
    a_n = [0] * 200
    a_n[1] = 1

    # Primes up to 200
    primes = [p for p in range(2, 200)
              if all(p % d != 0 for d in range(2, int(sqrt(p))+1))]

    for p in primes:
        ap = a_prime(p)
        # a_{p^k} via Hecke recurrence: a_{p^{k+1}} = a_p * a_{p^k} - a_{p^{k-1}}
        pk_vals = {0: 1, 1: ap}
        pk = p
        k = 1
        while pk < 200:
            a_n[pk] = pk_vals[k]
            pk_next = pk * p
            if pk_next < 200:
                pk_vals[k+1] = ap * pk_vals[k] - pk_vals.get(k-1, 0)
            pk = pk_next
            k += 1

    # Fill in composite n by multiplicativity
    for n in range(2, 200):
        if a_n[n] != 0:
            continue
        # Factor n
        temp = n
        factors = {}
        for p in primes:
            while temp % p == 0:
                factors[p] = factors.get(p, 0) + 1
                temp //= p
            if temp == 1:
                break
        # a_n = product of a_{p^k}
        val = 1
        for p, k in factors.items():
            pk = p**k
            if pk < 200 and a_n[pk] != 0:
                val *= a_n[pk]
            else:
                # Compute from Hecke recurrence
                ap = a_prime(p)
                a_pk = [1, ap]
                for j in range(2, k+1):
                    a_pk.append(ap * a_pk[-1] - a_pk[-2])
                val *= a_pk[k]
        a_n[n] = val

    for n in range(1, 31):
        print(f"  {n:5d} {a_n[n]:12.6f} {n%7:8d}")

    # Check multiplicativity
    print(f"\n  Multiplicativity check:")
    for p, q in [(2, 3), (2, 5), (3, 5), (2, 11), (3, 13)]:
        if p*q < 200:
            computed = a_n[p*q]
            product = a_n[p] * a_n[q]
            print(f"    a_{p*q} = {computed:.6f}, a_{p}*a_{q} = {product:.6f}, "
                  f"match: {'YES' if abs(computed - product) < 1e-8 else 'NO'}")

    # Compute L(s) at s = 2
    L_2 = sum(a_n[n] / n**2 for n in range(1, 200))
    print(f"\n  L(2) = {L_2:.10f}")

    # The functional equation: for a GL(2) form over Q at level 49:
    # Lambda(s) = (49/pi^2)^{s/2} Gamma(s/2)^2 L(s) = eps Lambda(1-s)

    # But wait: this is a form over K = Q(cos 2pi/7), not Q.
    # The L-function over K has different structure.

    # For a base-change from K to Q: the L-function over Q is
    # L(s, BC(f)) = L(s, f, sigma_1) * L(s, f, sigma_2) * L(s, f, sigma_3)
    # which is a degree-6 L-function.

    # For the individual L(s, f) over K: it's degree 2 at each prime ideal.

    # Let me compute the AUTOMORPHIC L-function over Q via base change:
    # L(s, BC) = prod_p L_p(s) where L_p depends on splitting type.

    print(f"\n  Base change L-function L(s, BC(f)) over Q:")
    print(f"  (degree 6, product of three GL(2) L-functions)\n")

    # For split p (p = 1,6 mod 7): three degree-1 local factors -> degree 6
    # L_p = prod_{i=1}^3 (1 - alpha_i p^{-s})^{-1} (1 - beta_i p^{-s})^{-1}
    # where alpha_i + beta_i = a_P_i and alpha_i * beta_i = 1.

    # For inert p: single degree-2 prime in K -> degree 6 over Q.

    # The KEY: the a_P values at each embedding are the three conjugates.
    # At split primes: a_P1 = v1/C, a_P2 = v2/C, a_P3 = v3/C

    a_P = [v1/C, v2/C, v3/C]  # normalized

    print(f"  At split primes: a_P1 = {a_P[0]:.6f}, a_P2 = {a_P[1]:.6f}, a_P3 = {a_P[2]:.6f}")
    print(f"  Product: {a_P[0]*a_P[1]*a_P[2]:.10f}")
    print(f"  Sum: {sum(a_P):.10f}")

    # The Satake parameters at each P_i:
    # alpha_i + beta_i = a_P_i, alpha_i * beta_i = 1
    # So: alpha_i = (a_P_i + sqrt(a_P_i^2 - 4)) / 2
    print(f"\n  Satake parameters at split primes:")
    for i in range(3):
        disc = a_P[i]**2 - 4
        if disc >= 0:
            alpha = (a_P[i] + sqrt(disc)) / 2
            beta = (a_P[i] - sqrt(disc)) / 2
            print(f"    P_{i+1}: alpha = {alpha:.6f}, beta = {beta:.6f}, "
                  f"|alpha| = {abs(alpha):.6f}")
        else:
            # Complex Satake parameters: |alpha| = 1 (Ramanujan!)
            theta = np.arccos(a_P[i] / 2)
            print(f"    P_{i+1}: alpha = e^{{i*{theta:.6f}}}, |alpha| = 1.000000 (RAMANUJAN)")

    return a_n, a_P


