def precise_hecke():
    """Pin down the exact Hecke eigenvalues."""
    print(f"\n{'='*72}")
    print("  PART 2: PRECISE HECKE EIGENVALUE STRUCTURE")
    print("=" * 72)

    N = 7
    S = {m: havelock_eigenvalue(m, N) for m in range(1, N)}
    S_max = max(abs(S[m]) for m in range(1, N))
    C = S_max / 2.0

    print(f"\n  The THREE distinct values taken by the Havelock spectrum:")
    v1 = S[1]  # mode 1 = mode 6
    v2 = S[2]  # mode 2 = mode 5
    v3 = S[3]  # mode 3 = mode 4

    print(f"    v_1 = S_1 = S_6 = {v1:.10f}")
    print(f"    v_2 = S_2 = S_5 = {v2:.10f}")
    print(f"    v_3 = S_3 = S_4 = {v3:.10f}")

    # These are the three Galois conjugates of a single element of K
    # Express in terms of alpha = 2cos(2pi/7):
    # v_k = sum_{j=1}^6 -log(2|sin(pi j/7)|) * cos(2pi j k/7) for k = 1,2,3

    # The KEY: cos(2pi j k/7) = T_k(cos(2pi j/7))/2 ... no, that's not right.
    # cos(2pi j k/7) is the PRODUCT of the action of sigma_k on zeta_7^j.

    # The three values are related by the Galois action:
    # sigma_1: zeta -> zeta, so cos(2pi j/7) -> cos(2pi j/7) [identity]
    # sigma_2: zeta -> zeta^2, so cos(2pi j/7) -> cos(4pi j/7) [permutes modes]
    # sigma_3: zeta -> zeta^3, so cos(2pi j/7) -> cos(6pi j/7) [permutes modes]

    # Under sigma_2: mode 1 -> mode 2, mode 2 -> mode 4 = mode 3, mode 3 -> mode 6 = mode 1
    # So: sigma_2(v_1) = v_2, sigma_2(v_2) = v_3, sigma_2(v_3) = v_1
    # This is the cyclic permutation (1 2 3).

    print(f"\n  Galois action: sigma_2(v_1) = v_2, sigma_2(v_2) = v_3, sigma_2(v_3) = v_1")
    print(f"  This is the 3-cycle (1 2 3) in Gal(K|Q) = Z/3Z.")

    # The minimal polynomial of v_1 over Q:
    # v_1 + v_2 + v_3 = Tr = sum of all S_m with m=1,...,3 (+ palindromic pairs)
    tr = v1 + v2 + v3
    print(f"\n  Tr(v) = v_1 + v_2 + v_3 = {tr:.10f}")

    # Sum of products of pairs
    s2 = v1*v2 + v1*v3 + v2*v3
    print(f"  e_2 = v_1*v_2 + v_1*v_3 + v_2*v_3 = {s2:.10f}")

    # Product
    prod = v1 * v2 * v3
    print(f"  e_3 = v_1*v_2*v_3 = {prod:.10f}")

    # Minimal polynomial: x^3 - tr*x^2 + s2*x - prod = 0
    print(f"\n  Minimal polynomial of v_1 over Q:")
    print(f"  x^3 - ({tr:.6f})*x^2 + ({s2:.6f})*x - ({prod:.6f}) = 0")

    # Check if the coefficients are recognizable
    print(f"\n  Are the coefficients rational?")
    for name, val in [("Tr", tr), ("e_2", s2), ("e_3", prod)]:
        # Try to identify as a/b with small b
        found = False
        for b in range(1, 20):
            a = round(val * b)
            if abs(val - a/b) < 1e-8:
                print(f"    {name} = {a}/{b} = {a/b:.10f} (exact)")
                found = True
                break
        if not found:
            print(f"    {name} = {val:.10f} (not a simple fraction)")

    # The key relationship: v_1 should be expressible in terms of alpha
    # v_1 = a + b*alpha + c*alpha^2 where a, b, c are rationals
    alphas = [ALPHA, ALPHA2, ALPHA3]
    M = np.array([[1, a_, a_**2] for a_ in alphas])
    v_vec = [v1, v2, v3]
    coeffs = np.linalg.solve(M, v_vec)

    print(f"\n  v_1 in the basis {{1, alpha, alpha^2}}:")
    print(f"  v_1 = {coeffs[0]:.10f} + {coeffs[1]:.10f}*alpha + {coeffs[2]:.10f}*alpha^2")

    # Try to identify coefficients as rationals
    for i, name in enumerate(["a", "b", "c"]):
        val = coeffs[i]
        found = False
        for b in range(1, 50):
            a = round(val * b)
            if abs(val - a/b) < 1e-6:
                print(f"    {name} = {a}/{b}")
                found = True
                break
        if not found:
            print(f"    {name} = {val:.10f} (not identified)")

    return v1, v2, v3, tr, s2, prod


