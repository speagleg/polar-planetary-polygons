def chebyshev_U(k, t):
    if k == 0:
        return 1.0
    if k == 1:
        return 2.0 * t
    U_prev2 = 1.0
    U_prev1 = 2.0 * t
    for _ in range(2, k + 1):
        U_curr = 2 * t * U_prev1 - U_prev2
        U_prev2 = U_prev1
        U_prev1 = U_curr
    return U_prev1


